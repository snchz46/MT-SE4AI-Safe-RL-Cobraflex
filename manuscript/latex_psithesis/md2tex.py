def referenced_figures() -> list[str]:
    names = set()
    for tex in list((HERE / "chapters").glob("*.tex")) + list((HERE / "appendices").glob("*.tex")) + \
            list((HERE / "front").glob("*.tex")):
        names.update(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex.read_text(encoding="utf-8")))
    return sorted(names)


def collect_figures(dest: Path) -> list[str]:
    copied = []
    for rel in referenced_figures():
        src = FIG_POOL / rel
        if not src.exists():
            warn(f"figure not found in pool: {rel}")
            continue
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        copied.append(rel)
    return copied


def write_zip() -> None:
    figs = HERE / "figures"
    collect_figures(figs)
    include = ["main.tex", "PSIThesis.cls", "literature.bib", "latexmkrc", "Makefile", "deps.txt", "README.md"]
    dirs = ["misc", "front", "chapters", "appendices", "fonts", "figures"]
    with zipfile.ZipFile(ZIP_OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for name in include:
            z.write(HERE / name, name)
        for d in dirs:
            for p in sorted((HERE / d).rglob("*")):
                if p.is_file() and p.suffix not in (".aux", ".log"):
                    z.write(p, p.relative_to(HERE).as_posix())
    print(f"wrote {ZIP_OUT} ({ZIP_OUT.stat().st_size / 1e6:.1f} MB)")


