class Inline:
    def __init__(self, labels: set[str], bib: list[BibEntry], doc_rel: str = ""):
        self.labels = labels
        self.doc_rel = doc_rel
        self.by_name: dict[str, dict[str, str]] = {}
        for e in bib:
            self.by_name.setdefault(e.first, {})[e.label_year] = e.key
        self.cited: set[str] = set()

    # -- citations ---------------------------------------------------------
    def _keys(self, names: str, years: list[str]) -> list[str] | None:
        names = names.strip()
        if not names or not (names[0].isupper()):
            return None
        first = re.split(r",\s*|\s+and\s+|\s+&\s+", re.sub(r"\s+et al\.?$", "", names))[0]
        table = self.by_name.get(norm_name(first))
        if not table:
            return None
        keys = []
        for y in years:
            if y not in table:
                return None
            keys.append(table[y])
        return keys

    def citations(self, s: str, put) -> str:
        def paren(m):
            lead, content = m.group(1), m.group(2)
            parts = [p.strip() for p in content.split(";")]
            rendered, pure, all_keys = [], True, []
            for p in parts:
                pm = re.match(rf"^(.*?),\s*({YEARS_RE})$", p)
                if not pm:
                    return m.group(0)
                words, years = pm.group(1).split(" "), re.split(r",\s*", pm.group(2))
                for k in range(len(words)):
                    keys = self._keys(" ".join(words[k:]), years)
                    if keys:
                        break
                else:
                    if re.search(r"[A-Z]", pm.group(1)):
                        warn(f"{self.doc_rel}: unresolved citation '({content})'")
                    return m.group(0)
                self.cited.update(keys)
                all_keys += keys
                if k:
                    pure = False
                rendered.append((" ".join(words[:k]), " ".join(words[k:]), keys))
            if pure:
                return lead.replace(" ", "") + put(("~" if lead else "") + r"\cite{" + ",".join(all_keys) + "}")
            out = []
            for prefix, names, keys in rendered:
                out.append((prefix + " " if prefix else "") + names + put(r"~\cite{" + ",".join(keys) + "}"))
            return lead + "(" + "; ".join(out) + ")"

        s = re.sub(rf"(\s?)\(([^()]*?[A-Za-z][^()]*?,\s*{YEARS_RE})\)", paren, s)

        out, pos = [], 0
        for m in re.finditer(rf"\s\(({YEARS_RE})\)", s):
            before = s[pos:m.start()]
            words = before.split(" ")
            years = re.split(r",\s*", m.group(1))
            for k in range(1, min(6, len(words)) + 1):
                keys = self._keys(" ".join(words[-k:]), years)
                if keys:
                    self.cited.update(keys)
                    out.append(before + put(r"~\cite{" + ",".join(keys) + "}"))
                    break
            else:
                warn(f"{self.doc_rel}: year in parentheses not resolved as a citation: "
                     f"'...{before[-40:]} ({m.group(1)})'")
                out.append(s[pos:m.end()])
            pos = m.end()
        out.append(s[pos:])
        return "".join(out)

    # -- cross references ---------------------------------------------------
    def xrefs(self, s: str, put) -> str:
        def ref(label: str, text: str, prefix: str = "") -> str:
            if label in self.labels:
                return put(prefix + r"\ref{" + label + "}")
            if not re.fullmatch(r"sec:\d+", label):    # "TR 5469 §7" is a clause of the standard
                warn(f"{self.doc_rel}: reference '{text}' has no target ({label})")
            return text

        def chapters(m):
            word, a, sep, b = m.group(1), m.group(2), m.group(3), m.group(4)
            out = word + ref(f"ch:{int(a):02d}", " " + a, "~")
            if b:
                out += sep + ref(f"ch:{int(b):02d}", b)
            return out

        s = re.sub(r"\b([Cc]hapters?)\s+(\d{1,2})\b(?:(\s*–\s*|\s+and\s+|\s+to\s+)(\d{1,2})\b)?", chapters, s)
        s = re.sub(r"\b(Figure|Table)\s+([A-I]|\d{1,2})\.(\d{1,2})\b",
                   lambda m: m.group(1) + ref(f"{'fig' if m.group(1) == 'Figure' else 'tab'}:"
                                              f"{m.group(2)}.{m.group(3)}", " " + m.group(2) + "." + m.group(3), "~"),
                   s)
        s = re.sub(r"\bAppendix\s+([A-I])\b", lambda m: "Appendix" + ref(f"app:{m.group(1)}", " " + m.group(1), "~"), s)
        s = re.sub(r"§([A-I0-9]{1,2}(?:\.\d+)*)", lambda m: ref(f"sec:{m.group(1)}", "§" + m.group(1), r"\S"), s)
        return s

    # -- code spans -------------------------------------------------------------
    @staticmethod
    def code(content: str) -> str:
        if content == "NOT SATISFIED":
            return r"\verdictnot{}"
        if content == "SATISFIED":
            return r"\verdictsat{}"
        out = []
        long_token = False
        for i, ch in enumerate(content):
            if i == 0 or content[i - 1] == " ":
                long_token = len(content[i:].split(" ", 1)[0]) > CODE_BREAK_LEN
            if ch == "\x01":
                out.append("|")
            elif ch == "_":
                out.append(r"\_\allowbreak{}" if long_token else r"\_")
            elif ch in "/.(," and long_token:
                out.append(ch + r"\allowbreak{}")
            elif ch in TEXT_ESCAPES and ch != "~":
                out.append(TEXT_ESCAPES[ch])
            elif ch == "~":
                out.append(r"\textasciitilde{}")
            else:
                out.append(ch)
        return r"\texttt{" + "".join(out) + "}"

    # -- the pipeline ---------------------------------------------------------
    def convert(self, s: str) -> str:
        store: list[str] = []

        def put(latex: str) -> str:
            store.append(latex)
            return f"\x00{len(store) - 1}\x00"

        s = s.replace("&nbsp;", " ").replace("\\|", "\x01")
        s = re.sub(r"`([^`]+)`", lambda m: put(self.code(m.group(1))), s)
        s = self.citations(s, put)
        s = self.xrefs(s, put)
        for rx, fn in ID_RULES:
            s = rx.sub(lambda m, fn=fn: put(fn(m)), s)
        s = "".join(TEXT_ESCAPES.get(ch, ch) for ch in s)
        s = s.replace("\x01", r"\textbar{}")
        s = re.sub(r"(\d) \\%", r"\1\\,\\%", s)
        s = re.sub(r"[⁰¹²³⁴⁵⁶⁷⁸⁹⁻]+", lambda m: r"\textsuperscript{" + "".join(SUPERSCRIPTS[c] for c in m.group(0)) + "}", s)
        s = s.replace("$-$1", "$-1$")
        for ch, name in GREEK.items():
            s = s.replace(ch, rf"$\{name}$")
        for ch, cmd in SYMBOLS.items():
            s = s.replace(ch, f"${cmd}$")
        s = s.replace("✓", r"\ding{51}").replace("✗", r"\ding{55}").replace("…", r"\ldots{}")
        # "gymnasium–Gazebo–ROS2": an en dash between words is not a break point
        # for TeX, and the compound is wider than a line of the text column
        s = re.sub(r"(?<=[A-Za-z])–(?=[A-Za-z])", r"–\\allowbreak{}", s)
        s = re.sub(r"(?<!\\)\$\$", "", s)     # merge adjacent maths: "$\sigma$$\theta$" -> "$\sigma\theta$"
        s = re.sub(r'"([^"]+)"', r"\\enquote{\1}", s)
        s = re.sub(r"“([^”]+)”", r"\\enquote{\1}", s)
        s = re.sub(r"(?<![\w\\])'([^'\s][^']*?)'(?!\w)", r"\\enquote*{\1}", s)
        s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
        s = re.sub(r"(?<![\w\\*])\*(?=\S)(.+?)(?<=\S)\*(?![\w*])", r"\\emph{\1}", s)
        if "*" in re.sub(r"\x00\d+\x00|\\enquote\*", "", s):
            warn(f"{self.doc_rel}: stray '*' after emphasis conversion: {s[:80]}")
        s = re.sub(r"(\x00\d+\x00)/", r"\1/\\allowbreak{}", s)   # C-04/C-06/C-03 may break at a slash
        while "\x00" in s:
            s = re.sub(r"\x00(\d+)\x00", lambda m: store[int(m.group(1))], s)
        return s


def plain(s: str) -> str:
    """Approximate the visible text of a Markdown cell, for width estimates."""
    s = s.replace("\\|", "|")
    s = re.sub(r"\((?:[^()]*?,\s*)?\d{4}[a-z]?(?:,\s*\d{4}[a-z]?)*\)", "[Xyz99]", s)
    return re.sub(r"[*`]", "", s).strip()


def short_caption(text: str) -> str:
    """First sentence of a caption, for the list of figures/tables."""
    depth = 0
    for i, ch in enumerate(text):
        if ch in "(`":
            depth += 1 if ch == "(" else 0
        elif ch == ")":
            depth = max(0, depth - 1)
        if ch == "." and depth == 0 and (i + 1 == len(text) or text[i + 1] == " ") and i > 20:
            return text[:i + 1]
    return text


