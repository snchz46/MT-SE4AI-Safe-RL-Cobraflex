def render_figure(inline: Inline, img, caption, label, where):
    rel = img["src"].replace("../figures/", "")
    if not (FIG_POOL / rel).exists():
        warn(f"{inline.doc_rel}: figure file missing: {rel}")
    alt = re.sub(r"^Figure\s+[A-Z0-9]+\.\d+\s+—\s+", "", img["alt"]).strip()
    docx_mm = img["width"] * 159.2 / 602.0      # width the DOCX build gives it
    if where == "appendix":
        env, width = "figure", f"{min(1.0, docx_mm / APPX_MM):.2f}\\textwidth"
    elif docx_mm <= TEXT_MM * 1.08:
        env, width = "figure", f"{min(1.0, docx_mm / TEXT_MM):.2f}\\textwidth"
    else:
        env, width = "figure*", f"{min(1.0, docx_mm / WIDE_MM):.2f}\\widefigurewidth"
    cap = inline.convert(caption)
    return "\n".join([
        rf"\begin{{{env}}}[{'!htbp' if where == 'appendix' else 'htbp'}]",
        rf"  \includegraphics[width={width}]{{{rel}}}",
        rf"  \caption[{inline.convert(alt)}]{{{cap}}}\label{{{label}}}",
        rf"\end{{{env}}}",
    ])


