def load_margin_notes() -> dict[str, list[dict]]:
    """Parse margin_notes.md: '## <file>' sections of '@ <anchor>' entries."""
    notes: dict[str, list[dict]] = {}
    path = HERE / "margin_notes.md"
    if not path.exists():
        return notes
    current = None
    entry = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^## (body/\S+\.md)\s*$", line)
        if m:
            current = notes.setdefault(m.group(1), [])
            entry = None
            continue
        if current is None:
            continue
        m = re.match(r"^@(prelim)?\s+(.+?)\s*$", line)
        if m:
            entry = dict(kind="prelim" if m.group(1) else "note", anchor=m.group(2), text="", used=False)
            current.append(entry)
        elif not line.strip():
            entry = None
        elif entry is not None:
            entry["text"] = (entry["text"] + " " + line.strip()).strip()
    return notes


MARGIN_NOTES = load_margin_notes()

HEADER = ("% GENERATED by md2tex.py from ../draft_v5_en/{src} -- do not edit by hand.\n"
          "% Change the Markdown and run `python md2tex.py`; edits here are overwritten.\n")


def render_doc(doc: Doc, labels: set[str], bib: list[BibEntry]) -> tuple[str, set[str]]:
    inline = Inline(labels, bib, doc.rel)
    letter = doc.md.name[0] if doc.kind == "appendix" else None
    where = {"chapter": "body", "appendix": "appendix", "front": "front"}[doc.kind]
    plan = {id(b): (cmd, title, label) for b, cmd, title, label in heading_plan(doc)}
    out = [HEADER.format(src=doc.rel)]
    if letter and any(k[0] == letter for k in SUPPLIED_TABLE_HEADERS):
        out.append("% NOTE: the source tables carry no header row; the headers below are supplied\n"
                   "% by md2tex.py (SUPPLIED_TABLE_HEADERS) from the column contents.\n")
    blocks = doc.blocks
    tcount = 0
    skip = set()
    front_name = doc.md.stem
    notes = MARGIN_NOTES.get(doc.rel, [])

    def running(text: str) -> str:
        """Convert running text, attaching the margin notes anchored in it."""
        markers = {}
        for n in notes:
            if n["used"]:
                continue
            at = text.find(n["anchor"])
            if at < 0:
                continue
            end = at + len(n["anchor"])
            while end < len(text) and text[end] == "*":     # land after a closing ** or *
                end += 1
            key = f"\x03{len(markers)}\x03"
            text = text[:end] + key + text[end:]
            markers[key] = n
            n["used"] = True
        latex = inline.convert(text)
        for key, n in markers.items():
            tex = r"\prelimflag{}" if n["kind"] == "prelim" else r"\sidenote{" + inline.convert(n["text"]) + "}"
            if key not in latex:
                warn(f"{doc.rel}: margin note lost in conversion: '{n['anchor']}'")
            latex = latex.replace(key, tex)
        return latex

    for i, b in enumerate(blocks):
        if i in skip:
            continue
        k = b["kind"]
        if k == "heading":
            cmd, title, label = plan[id(b)]
            if doc.kind == "front" and front_name in ("10_abstract", "15_preface", "05_declaration"):
                continue
            t = inline.convert(title)
            short = re.sub(r"[*`]", "", title)
            opt = f"[{inline.convert(short)}]" if t != inline.convert(short) else ""
            out.append(f"\\{cmd}{opt}{{{t}}}" + (f"\n\\label{{{label}}}" if label else "") + "\n")
        elif k == "para":
            m = CAPTION_RE.match(b["text"])
            if m:
                continue        # consumed by the figure/table before it
            out.append(running(b["text"]) + "\n")
        elif k == "img":
            nxt = blocks[i + 1] if i + 1 < len(blocks) else None
            m = CAPTION_RE.match(nxt["text"]) if nxt and nxt["kind"] == "para" else None
            if not m:
                warn(f"{doc.rel}: image {b['src']} has no caption paragraph")
                continue
            label = f"fig:{m.group(2)}.{m.group(3)}"
            out.append(render_figure(inline, b, m.group(4), label, where) + "\n")
            skip.add(i + 1)
        elif k == "table":
            tcount += 1
            supplied = SUPPLIED_TABLE_HEADERS.get((letter, tcount)) if letter else None
            header, rows, aligns = parse_table(b, supplied)
            nxt = blocks[i + 1] if i + 1 < len(blocks) else None
            caption = short = label = None
            if nxt and nxt["kind"] == "para":
                m = CAPTION_RE.match(nxt["text"])
                if m and m.group(1) == "Table":
                    caption = m.group(4)
                    label = f"tab:{m.group(2)}.{m.group(3)}"
                    skip.add(i + 1)
                elif re.fullmatch(r"\*[^*].*[^*]\*", nxt["text"]):
                    caption = nxt["text"][1:-1]
                    skip.add(i + 1)
            if letter:
                label = f"tab:{letter}.{tcount}"
                if caption is None:
                    caption = SUPPLIED_TABLE_CAPTIONS.get((letter, tcount))
                    if caption is None:
                        warn(f"{doc.rel}: table {tcount} has no caption")
            if caption:
                short = short_caption(caption)
            out.append(render_table(inline, header, rows, aligns, where, caption, short, label) + "\n")
        elif k == "quote":
            paras = [running(p) for p in b["paras"]]
            out.append("\\begin{quote}\n" + "\n\n".join(paras) + "\n\\end{quote}\n")
        elif k == "list":
            env = "enumerate" if b["ordered"] else "itemize"
            items = "\n".join("  \\item " + running(it) for it in b["items"])
            out.append(f"\\begin{{{env}}}\n{items}\n\\end{{{env}}}\n")
        elif k == "code":
            size = r"\footnotesize" if len(b["lines"]) > 20 else r"\small"
            body = "\n".join(b["lines"])
            out.append("\\begingroup\n" + size + "\n\\begin{verbatim}\n" + body + "\n\\end{verbatim}\n\\endgroup\n")
    text = "\n".join(out)
    if front_name == "05_declaration":
        text = render_declaration(doc, inline)
    return text, inline.cited


def render_declaration(doc: Doc, inline: Inline) -> str:
    paras = [b["text"] for b in doc.blocks if b["kind"] == "para"]
    body, place, name = paras[0], paras[1], paras[2]
    return HEADER.format(src=doc.rel) + "\n".join([
        r"\begin{declaration}",
        r"\addchaptertocentry{\authorshipname}",
        "",
        r"\noindent " + inline.convert(body),
        "",
        r"\bigskip\bigskip",
        "",
        r"\noindent",
        r"\begin{tabular}[b]{@{}l@{}}",
        "\t" + inline.convert(place),
        r"\end{tabular}",
        r"\hspace{\fill}",
        r"\begin{tabular}[b]{@{}l@{}}",
        "\t\\rule{42mm}{0.4pt}\\\\",
        "\t" + inline.convert(name),
        r"\end{tabular}",
        "",
        r"\end{declaration}",
        "",
    ])


