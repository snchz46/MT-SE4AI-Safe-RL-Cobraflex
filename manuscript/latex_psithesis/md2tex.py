#!/usr/bin/env python3
"""md2tex.py -- regenerate the PSIThesis LaTeX sources from ../draft_v5_en.

The .tex files under chapters/, appendices/ and front/ and literature.bib are
GENERATED by this script. Edit the Markdown in manuscript/draft_v5_en/ and
re-run; hand edits to the generated files are overwritten.

    python md2tex.py            regenerate every .tex file and literature.bib
    python md2tex.py --figures  also copy the referenced figures into ./figures
    python md2tex.py --zip      regenerate, collect figures and write
                                ../thesis-psithesis-overleaf.zip

No third-party packages: runs on the plain Python of the Windows authoring
host as well as on the compute host.

What the conversion does, in the order it matters for the typeset result:

* Structure. "# Chapter N -- Title" becomes \\chapter + \\label{ch:NN},
  "# Appendix X -- Title" \\chapter + \\label{app:X}; numbered headings get
  \\label{sec:<number as written>}, so "§7.2.4" in the prose resolves.
* Citations. "(Author et al., 2025)" becomes \\cite{key}; the narrative form
  "Author et al. (2025)" keeps the names as written and replaces only the year
  with \\cite{key}. Keys come from the same parse of 0_bibliography.md that
  writes literature.bib, so a citation that does not resolve is reported.
* Cross references. "Chapter 8", "Figure 7.1", "Table F.1", "Appendix G" and
  "§9.3.6" link to their labels; the words stay as the author wrote them.
* Identifiers. H-XX, SR-XXX, C-XX, SC-*-XX, M-*, D-NN go through the macros
  of misc/thesis-commands.tex, which never break across a line.
* Tables. The layout is computed from the content, see layout_table(). Body
  tables that do not fit the 107 mm text column become table* floats over
  text + margin (164.6 mm). Appendix tables are longtables with a repeated
  header over the full-width appendix geometry that main.tex switches to,
  because a page-breaking table cannot follow the margin column from odd to
  even pages -- that was the defect of the hand conversion.
"""

