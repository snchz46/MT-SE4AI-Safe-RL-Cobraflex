def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--figures", action="store_true", help="copy referenced figures into ./figures")
    ap.add_argument("--zip", action="store_true", help="write ../thesis-psithesis-overleaf.zip")
    args = ap.parse_args()

    bib = load_bibliography()
    docs = build_docs()
    labels: set[str] = set()
    for d in docs:
        for _b, cmd, _t, label in heading_plan(d):
            if label:
                labels.add(label)
        figure_and_table_labels(d, labels)

    cited: set[str] = set()
    for d in docs:
        text, c = render_doc(d, labels, bib)
        cited |= c
        target = HERE / d.out
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")

    bib_text = ["% literature.bib -- GENERATED by md2tex.py from ../draft_v5_en/back/0_bibliography.md.",
                "% Do not edit by hand. Keys: <first author surname><year><suffix>; standards by number.", ""]
    bib_text += [e.bibtex() + "\n" for e in bib]
    (HERE / "literature.bib").write_text("\n".join(bib_text), encoding="utf-8", newline="\n")

    for rel, entries in MARGIN_NOTES.items():
        for n in entries:
            if not n["used"]:
                warn(f"margin_notes.md: anchor not found in running text of {rel}: '{n['anchor']}'")

    uncited = [e.key for e in bib if e.key not in cited]
    if uncited:
        warn(f"bibliography entries never cited in the text (still printed via \\nocite): {uncited}")

    if args.figures or args.zip:
        n = len(collect_figures(HERE / "figures"))
        print(f"collected {n} figures into ./figures")
    if args.zip:
        write_zip()

    print(f"{len(docs)} files and literature.bib ({len(bib)} entries) written")
    for w in WARNINGS:
        print("WARNING:", w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
