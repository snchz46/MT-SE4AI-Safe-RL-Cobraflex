class Doc:
    def __init__(self, md: Path, out: str, kind: str):
        self.md, self.out, self.kind = md, out, kind
        self.blocks = parse_blocks(md.read_text(encoding="utf-8"))
        self.rel = md.relative_to(SRC).as_posix()


def build_docs() -> list[Doc]:
    docs = []
    for md in sorted((SRC / "body").glob("*.md")):
        nn = md.name[:2]
        docs.append(Doc(md, f"chapters/chapter{nn}.tex", "chapter"))
    for md in sorted((SRC / "back").glob("[A-Z]_*.md")):
        docs.append(Doc(md, f"appendices/appendix{md.name[0]}.tex", "appendix"))
    for name, out in (("10_abstract", "front/abstract.tex"), ("15_preface", "front/preface.tex"),
                      ("05_declaration", "front/declaration.tex"),
                      ("40_abbreviations", "front/abbreviations.tex")):
        docs.append(Doc(SRC / "front" / f"{name}.md", out, "front"))
    return docs


def heading_plan(doc: Doc) -> list[tuple[Block, str, str, str]]:
    """Return (block, command, title, label) for every heading of a doc."""
    h1 = [b for b in doc.blocks if b["kind"] == "heading" and b["level"] == 1]
    shift = 1 if len(h1) > 1 else 0
    out = []
    chapter_id = None
    counters = [0, 0, 0]
    first = True
    for b in doc.blocks:
        if b["kind"] != "heading":
            continue
        text = b["text"]
        if first:
            first = False
            m = re.match(r"^(Chapter|Appendix)\s+([A-Z0-9]+)\s+—\s+(.*)$", text)
            if m:
                chapter_id = m.group(2) if m.group(1) == "Appendix" else f"{int(m.group(2)):02d}"
                label = ("app:" if m.group(1) == "Appendix" else "ch:") + chapter_id
                if m.group(1) == "Chapter":
                    chapter_id = str(int(m.group(2)))
                out.append((b, "chapter", m.group(3), label))
            else:
                out.append((b, "addchap", text, ""))
            continue
        depth = b["level"] - 2 + shift        # 0 section, 1 subsection, 2 subsubsection
        depth = max(0, min(2, depth))
        counters[depth] += 1
        for d in range(depth + 1, 3):
            counters[d] = 0
        computed = ".".join([chapter_id or "?"] + [str(c) for c in counters[:depth + 1]])
        m = re.match(r"^([A-Z0-9]+(?:\.\d+)+)\s+(.*)$", text)
        if m:
            number, title = m.group(1), m.group(2)
            if number != computed:
                warn(f"{doc.rel}: heading '{text}' numbered {number}, LaTeX will number it {computed}")
        else:
            number, title = computed, text
        cmd = ("section", "subsection", "subsubsection")[depth]
        out.append((b, cmd, title, f"sec:{number}"))
    return out


