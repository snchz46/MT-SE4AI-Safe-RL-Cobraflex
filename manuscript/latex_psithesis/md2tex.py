class Block(dict):
    pass


def parse_blocks(text: str) -> list[Block]:
    lines = text.replace("\r\n", "\n").split("\n")
    blocks: list[Block] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if not s or re.fullmatch(r"::[a-z-]+::", s) or s == "---":
            i += 1
            continue
        if s.startswith("```"):
            lang = s[3:].strip()
            body = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                body.append(lines[i])
                i += 1
            blocks.append(Block(kind="code", lang=lang, lines=body))
            i += 1
            continue
        m = re.match(r"^(#{1,4})\s+(.*)$", s)
        if m:
            blocks.append(Block(kind="heading", level=len(m.group(1)), text=m.group(2).strip()))
            i += 1
            continue
        if s.startswith("<img"):
            src = re.search(r'src="([^"]+)"', s).group(1)
            alt = re.search(r'alt="([^"]*)"', s).group(1)
            width = int(re.search(r'width="(\d+)"', s).group(1))
            blocks.append(Block(kind="img", src=src, alt=alt, width=width))
            i += 1
            continue
        if s.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i].strip())
                i += 1
            blocks.append(Block(kind="table", rows=rows))
            continue
        if s.startswith(">"):
            paras, cur = [], []
            while i < len(lines) and lines[i].strip().startswith(">"):
                content = lines[i].strip()[1:].strip()
                if content:
                    cur.append(content)
                elif cur:
                    paras.append(" ".join(cur))
                    cur = []
                i += 1
            if cur:
                paras.append(" ".join(cur))
            blocks.append(Block(kind="quote", paras=paras))
            continue
        if re.match(r"^(-|\d+\.)\s+", s):
            ordered = bool(re.match(r"^\d+\.", s))
            items = []
            while i < len(lines) and re.match(r"^\s*(-|\d+\.)\s+", lines[i]):
                items.append(re.sub(r"^\s*(-|\d+\.)\s+", "", lines[i]).strip())
                i += 1
                while i < len(lines) and lines[i].strip() and not re.match(
                        r"^\s*(-|\d+\.)\s+|^\s*[#|<>`]", lines[i]):
                    items[-1] += " " + lines[i].strip()
                    i += 1
            blocks.append(Block(kind="list", ordered=ordered, items=items))
            continue
        para = []
        while i < len(lines) and lines[i].strip() and not re.match(
                r"^\s*(#{1,4}\s|```|<img|\||>|(-|\d+\.)\s)", lines[i]):
            para.append(lines[i].strip())
            i += 1
        blocks.append(Block(kind="para", text=" ".join(para)))
    return blocks


CAPTION_RE = re.compile(r"^\*(Figure|Table)\s+([A-Z0-9]+)\.(\d+)\s+—\s+(.*)\*$", re.S)


