def figure_and_table_labels(doc: Doc, labels: set[str]) -> None:
    letter = doc.md.name[0] if doc.kind == "appendix" else None
    tcount = 0
    for i, b in enumerate(doc.blocks):
        if b["kind"] == "para":
            m = CAPTION_RE.match(b["text"])
            if m:
                pfx = "fig" if m.group(1) == "Figure" else "tab"
                if pfx == "tab" and letter:
                    continue
                labels.add(f"{pfx}:{m.group(2)}.{m.group(3)}")
        if b["kind"] == "table" and letter:
            tcount += 1
            labels.add(f"tab:{letter}.{tcount}")


