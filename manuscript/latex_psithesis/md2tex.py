def split_row(row: str) -> list[str]:
    row = row.replace("\\|", "\x02")
    cells = [c.strip().replace("\x02", "\\|") for c in row.strip().strip("|").split("|")]
    return cells


CODE_BREAK_LEN = 16     # code tokens longer than this may break after _ / . ( ,
CODE_BREAK_AFTER = r"(?<=[_/.(,])"
HYPHENATE_MIN = 10      # prose words longer than this may be hyphenated in a table cell


def unbreakable_len(cell: str, header: bool = False) -> int:
    """Longest run a cell can NOT break inside: identifiers, short code tokens,
    and -- for prose -- words up to HYPHENATE_MIN characters (longer ones
    hyphenate). Header words never hyphenate."""
    longest = 1.0
    for m in re.finditer(r"`([^`]+)`", cell):
        for t in m.group(1).split():
            parts = [t] if len(t) <= CODE_BREAK_LEN else re.split(CODE_BREAK_AFTER, t)
            longest = max(longest, max(len(p) for p in parts) * 1.1)   # Iosevka: every glyph 0.415 em
    prose = re.sub(r"`[^`]+`", " ", cell)
    for t in re.split(r"[\s/]+", plain(prose)):
        if not t:
            continue
        if ID_TOKEN_RE.match(t) or header:
            longest = max(longest, vis_len(t))
        else:
            for p in re.split(r"(?<=[-–])", t):
                longest = max(longest, vis_len(p) if len(p) <= HYPHENATE_MIN else HYPHENATE_MIN)
    return longest


def vis_len(s: str) -> float:
    """Length in average characters: capitals and figures are wider."""
    return sum(1.45 if c.isupper() else 1.05 if c.isdigit() else 1.0 for c in s)


def table_height(rows_len, widths, cw):
    """Estimated height in text lines: each row is as tall as its tallest cell."""
    height = 0.0
    for r in rows_len:
        lines = [n * cw * 1.08 / max(w - 0.8, 1.0) for n, w in zip(r, widths)]
        # the tallest cell sets the row; a small share of the other cells keeps
        # a column that is never the tallest from being squeezed to its minimum
        height += max(lines) + 0.35 + 0.08 * sum(lines)
    return height


def rotatable(header, rows):
    """Columns of short marks (check marks, "partial", "30/30") under a long
    header: the header is what makes them wide, so it is set rotated."""
    body = [max((len(plain(r[j])) for r in rows), default=0) for j in range(len(header))]
    cand = [body[j] <= 8 and len(plain(header[j])) >= 6 and len(plain(header[j])) > body[j]
            for j in range(len(header))]
    # rotate a block of mark columns, never a lone column (a rotated "Assumption"
    # over S1..S5 reads worse than a wrapped one)
    if sum(cand) < 2 or not any(c and len(plain(h)) > 9 for c, h in zip(cand, header)):
        return [False] * len(header)
    return cand


def layout_widths(header, rows, width_mm, size, rotate=None):
    """Column widths that minimise the estimated table height.

    Every column starts at the width of its longest unbreakable run; the
    remaining space is handed out in small steps to whichever column shortens
    the table most. A column never grows past its longest cell, so short
    columns (IDs, S/E/C ratings, check marks) stay tight and the prose columns
    get the room."""
    cw = CHAR_MM[size]
    ncol = len(header)
    content = width_mm - 2 * SEP_MM * (ncol - 1) - 1.0     # 1 mm reserve against rounding
    rotate = rotate or [False] * ncol
    rows_len = [[len(plain(c)) for c in r] for r in rows] + \
        [[0 if rot else len(plain(h)) * 1.3 for h, rot in zip(header, rotate)]]
    maxc = [max(r[j] for r in rows_len) * cw + 1.0 for j in range(ncol)]
    minc = [max([unbreakable_len(r[j]) for r in rows] +
                [3 if rotate[j] else unbreakable_len(header[j], True) * 1.3]) * cw + 1.0
            for j in range(ncol)]
    maxc = [max(a, b) for a, b in zip(maxc, minc)]
    if sum(maxc) <= content:
        return "natural", maxc
    if sum(minc) > content:
        return "overflow", minc
    widths = list(minc)
    step = 0.5
    spare = content - sum(widths)
    while spare > 1e-6:
        inc = min(step, spare)
        base = table_height(rows_len, widths, cw)
        best, gain = None, 0.0
        for j in range(ncol):
            if widths[j] + inc > maxc[j] + 1e-6:
                continue
            trial = widths[:]
            trial[j] += inc
            g = base - table_height(rows_len, trial, cw)
            if g > gain + 1e-9:
                best, gain = j, g
        if best is None:
            # nothing shortens the table any more: widen the columns that are
            # furthest from their natural width, proportionally
            room = [maxc[j] - widths[j] for j in range(ncol)]
            if sum(room) <= 1e-6:
                room = [1.0] * ncol
            widths = [w + spare * r / sum(room) for w, r in zip(widths, room)]
            break
        widths[best] += inc
        spare -= inc
    return "fixed", widths


def estimate_height(header, rows, widths, size):
    cw, lh = CHAR_MM[size], LINE_MM[size]
    total = 0.0
    for r in [header] + rows:
        lines = max(math.ceil(len(plain(c)) * cw * 1.08 / max(w - 1.0, 1.0)) or 1 for c, w in zip(r, widths))
        total += lines * lh + 0.8
    return total


def column_spec(aligns, widths, kind):
    spec = []
    for a, w in zip(aligns, widths):
        if kind == "natural":
            spec.append({"c": "c", "r": "r"}.get(a, "l"))
        else:
            ragged = {"c": r"\centering", "r": r"\RaggedLeft"}.get(a, r"\RaggedRight")
            spec.append(rf">{{{ragged}\arraybackslash}}p{{{w:.1f}mm}}")
    return "@{}" + "".join(spec) + "@{}"


def layout_widths_rot(header, rows, width_mm, size):
    kind, widths = layout_widths(header, rows, width_mm, size)
    rot = rotatable(header, rows)
    if kind != "natural" and any(rot):
        kind, widths = layout_widths(header, rows, width_mm, size, rot)
        return kind, widths, rot
    return kind, widths, [False] * len(header)


def layout_table(header, rows, aligns, where):
    """Pick container, font size and column widths from the content.

    where: 'body'     -- a float; text column if it fits, else table* over
                         text + margin column
           'appendix' -- longtable over the full-width appendix geometry
           'front'    -- longtable inside the text column
    """
    if where == "body":
        kind, widths = layout_widths(header, rows, TEXT_MM, "small")
        if kind == "natural":
            return dict(env="table", size="small", kind=kind, widths=widths, width=TEXT_MM,
                        rotate=[False] * len(header))
        for size in ("small", "footnotesize", "scriptsize"):
            kind, widths, rot = layout_widths_rot(header, rows, WIDE_MM, size)
            if kind != "overflow" and estimate_height(header, rows, widths, size) < PAGE_TEXT_MM * 0.8:
                return dict(env="table*", size=size, kind=kind, widths=widths, width=WIDE_MM, rotate=rot)
        warn(f"body table with header {header[:3]} is too large for one float")
        return dict(env="table*", size="scriptsize", kind=kind, widths=widths, width=WIDE_MM, rotate=rot)
    width = APPX_MM if where == "appendix" else TEXT_MM
    sizes = ("small", "footnotesize", "scriptsize") if where == "appendix" else ("small", "footnotesize")
    for size in sizes:
        kind, widths, rot = layout_widths_rot(header, rows, width, size)
        if kind == "natural" or (kind == "fixed" and size != "small"):
            # a table that fits comfortably on one page is better as a float:
            # a longtable never floats, so it drags half-empty pages behind it
            short = where == "appendix" and estimate_height(header, rows, widths, size) < PAGE_TEXT_MM * 0.5
            return dict(env="table" if short else "longtable", size=size, kind=kind, widths=widths,
                        width=width, rotate=rot)
    return dict(env="longtable", size=sizes[-1], kind=kind, widths=widths, width=width, rotate=rot)


def render_table(inline: Inline, header, rows, aligns, where, caption=None, short=None, label=None):
    plan = layout_table(header, rows, aligns, where)
    if plan["kind"] == "overflow":
        warn(f"{inline.doc_rel}: table {label or header[:2]} cannot fit even at {plan['size']}")
    spec = column_spec(aligns, plan["widths"], "natural" if plan["kind"] == "natural" else "fixed")
    n = len(header)
    head = " & ".join(
        "" if not h else
        (r"\rotatebox{90}{\tabhead{" + inline.convert(h) + "}}" if rot else r"\tabhead{" + inline.convert(h) + "}")
        for h, rot in zip(header, plan["rotate"])) + r" \\"
    multiline = plan["kind"] != "natural" and estimate_height(header, rows, plan["widths"], plan["size"]) > \
        (len(rows) + 1) * (LINE_MM[plan["size"]] + 0.8) * 1.3
    body = []
    for r in rows:
        body.append("  " + " & ".join(inline.convert(c) for c in r) + r" \\")
        if multiline:
            body.append(r"  \addlinespace[2pt]")
    if multiline and body:
        body.pop()
    cap = ""
    if caption:
        cap = r"\caption" + (f"[{inline.convert(short)}]" if short and short != caption else "") + \
            "{" + inline.convert(caption) + "}" + (r"\label{" + label + "}" if label else "")
    size = "\\" + plan["size"]
    out = [f"% layout: {plan['env']}, {plan['kind']}, \\{plan['size']}, "
           f"{sum(plan['widths']) + 2 * SEP_MM * (n - 1):.0f} of {plan['width']:.0f} mm"]
    if plan["env"] == "longtable":
        out += [r"\begingroup", size + rf"\setlength{{\tabcolsep}}{{{TABCOLSEP_PT:g}pt}}",
                r"\setlength{\LTleft}{0pt}\setlength{\LTright}{\fill}\setlength{\LTcapwidth}{\textwidth}",
                rf"\begin{{longtable}}{{{spec}}}"]
        if cap:
            out.append(cap + r" \\")
        out += [r"  \toprule", "  " + head, r"  \midrule", r"  \endfirsthead",
                rf"  \multicolumn{{{n}}}{{@{{}}l}}{{\emph{{(continued)}}}} \\",
                r"  \toprule", "  " + head, r"  \midrule", r"  \endhead",
                r"  \midrule", rf"  \multicolumn{{{n}}}{{r@{{}}}}{{\emph{{(continued on next page)}}}} \\",
                r"  \endfoot", r"  \bottomrule", r"  \endlastfoot"]
        out += body
        out += [r"\end{longtable}", r"\endgroup"]
    else:
        env = plan["env"]
        # appendices: the table belongs right where the register text calls it
        out += [rf"\begin{{{env}}}[{'!htbp' if where == 'appendix' else 'htbp'}]"]
        if cap:
            out.append(cap)
        out += [size + rf"\setlength{{\tabcolsep}}{{{TABCOLSEP_PT:g}pt}}", rf"\begin{{tabular}}{{{spec}}}",
                r"  \toprule", "  " + head, r"  \midrule"]
        out += body
        out += [r"  \bottomrule", r"\end{tabular}", rf"\end{{{env}}}"]
    return "\n".join(out)


def parse_table(block, supplied_header=None):
    rows = [split_row(r) for r in block["rows"]]
    if supplied_header:
        header, data, aligns = supplied_header, rows, ["l"] * len(supplied_header)
    else:
        header, sep, data = rows[0], rows[1], rows[2:]
        aligns = []
        for c in sep:
            c = c.strip()
            aligns.append("c" if c.startswith(":") and c.endswith(":") else "r" if c.endswith(":") else "l")
    n = len(header)
    data = [(r + [""] * n)[:n] for r in data]
    return header, data, aligns


